import { writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const backendUrl = process.env.BACKEND_URL ?? 'http://localhost:4000';
const source = new URL('/openapi.json', backendUrl);
const target = new URL('../src/lib/api-types.ts', import.meta.url);

const ast = await openapiTS(source);
const header = `// Generated by \`npm run gen:api\` from olli-backend-service ${source.pathname}. Do not edit.\n\n`;
await writeFile(target, header + astToString(ast));
process.stdout.write(`API types written to src/lib/api-types.ts from ${source.href}\n`);
